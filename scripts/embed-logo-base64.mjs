/**
 * Generates lib/logo-base64.ts from assets/images/PackersMoversLogo.png
 * Run: node scripts/embed-logo-base64.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pngPath = join(root, 'assets', 'images', 'PackersMoversLogo.png');
const outPath = join(root, 'lib', 'logo-base64.ts');

const base64 = readFileSync(pngPath).toString('base64');

writeFileSync(
  outPath,
  `/** Auto-generated by scripts/embed-logo-base64.mjs — do not edit manually */\nexport const LOGO_PNG_BASE64 = '${base64}';\nexport const LOGO_DATA_URI = 'data:image/png;base64,${base64}';\n`,
  'utf8',
);

console.log(`Wrote ${outPath} (${base64.length} chars)`);
